export type ArticleQuestionCard = {
  title: string;
  example: string;
};

export type ArticleInlineImage = {
  src: string;
  alt: string;
  caption?: string;
  aspect?: "3/2" | "16/9";
};

export type ArticleEyecatch = {
  src: string;
  alt: string;
  width: number;
  height: number;
};

// 記事内から関連ページへ誘導するリンクカード。内部パス専用（外部URLは渡さない運用）。
export type ArticleLinkCard = {
  href: string;
  title: string;
  description: string;
  ctaLabel?: string;
};

export type ArticleSection = {
  heading: string;
  paragraphs: string[];
  // 段落の後に描画する箇条書き（テンプレート提示などに使う）。任意。
  list?: string[];
  // 段落の後に描画する質問テンプレート。任意。
  cards?: ArticleQuestionCard[];
  // 段落の後に描画する記事内画像。読み疲れを防ぐ視覚的な区切りに使う。任意。
  image?: ArticleInlineImage;
  // セクション末尾に描画する内部リンクカード。任意。
  linkCard?: ArticleLinkCard;
};

export type Article = {
  slug: string;
  title: string;
  description: string;
  datePublished: string; // YYYY-MM-DD
  dateModified?: string;
  // ヒーローのピルに表示するカテゴリラベル。任意。
  category?: string;
  // 記事ヒーローとOGP/構造化データで使うアイキャッチ。任意。
  eyecatch?: ArticleEyecatch;
  // 見出しなしの導入文（H1直下に描画）。任意。
  lead?: string[];
  // 記事末尾ストアCTAの文言差し替え。未指定時は既定文言（日記文脈）で描画する。
  cta?: { title: string; body: string };
  sections: ArticleSection[];
};

