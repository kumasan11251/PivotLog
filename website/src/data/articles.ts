// 記事コンテンツの単一ソース。
// ARTICLES に記事を追加するだけで、一覧・詳細・JSON-LD・prerender・sitemap（手動追記）が有効になる。
// MDX やリッチブロックは入れず、見出し＋段落配列の最小構造にとどめる。

// 質問テンプレート（質問＋記入例）を見せるためのブロック。
export type ArticleQuestionCard = {
  title: string;
  example: string;
};

export type ArticleInlineImage = {
  src: string;
  alt: string;
  caption?: string;
};

export type ArticleEyecatch = {
  src: string;
  alt: string;
  width: number;
  height: number;
};

export type ArticleSection = {
  heading: string;
  paragraphs: string[];
  // 段落の後に描画する箇条書き（テンプレート提示などに使う）。任意。
  list?: string[];
  // 段落の後に描画する質問テンプレート。任意。
  cards?: ArticleQuestionCard[];
  // 段落の後に描画する記事内画像。読み疲れを防ぐ視覚的な区切りに使う。任意。
  image?: ArticleInlineImage;
};

export type Article = {
  slug: string;
  title: string;
  description: string;
  datePublished: string; // YYYY-MM-DD
  dateModified?: string;
  // ヒーローのピルに表示するカテゴリラベル。任意。
  category?: string;
  // 記事ヒーローとOGP/構造化データで使うアイキャッチ。任意。
  eyecatch?: ArticleEyecatch;
  // 見出しなしの導入文（H1直下に描画）。任意。
  lead?: string[];
  sections: ArticleSection[];
};

